// Clawd: his low-resolution pixels for the look (clawd.ts), smoothed with
// scale3x and shaded: a lit top, a darker underside and right side, an
// outline a shade of his own color. Cached per look.
const clawdCache = new Map<string, HdArt>()
const shadeOf = (c: Rgb, k: number): Rgb => [Math.min(255, Math.round(c[0] * k)), Math.min(255, Math.round(c[1] * k)), Math.min(255, Math.round(c[2] * k))]
const lift = (c: Rgb, k: number): Rgb => [Math.round(c[0] + (255 - c[0]) * k), Math.round(c[1] + (255 - c[1]) * k), Math.round(c[2] + (255 - c[2]) * k)]

function scale3x(g: string[][]): string[][] {
  const H = g.length
  const W = g[0]!.length
  const at = (x: number, y: number) => (x >= 0 && y >= 0 && x < W && y < H ? g[y]![x]! : '.')
  const out: string[][] = Array.from({ length: H * 3 }, () => new Array<string>(W * 3).fill('.'))
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const [A, B, C, D, E, F, G, Hh, I] = [at(x - 1, y - 1), at(x, y - 1), at(x + 1, y - 1), at(x - 1, y), at(x, y), at(x + 1, y), at(x - 1, y + 1), at(x, y + 1), at(x + 1, y + 1)]
      const e = [E, E, E, E, E, E, E, E, E]
      if (B !== Hh && D !== F) {
        e[0] = D === B ? D : E
        e[1] = (D === B && E !== C) || (B === F && E !== A) ? B : E
        e[2] = B === F ? F : E
        e[3] = (D === B && E !== G) || (D === Hh && E !== A) ? D : E
        e[5] = (B === F && E !== I) || (Hh === F && E !== C) ? F : E
        e[6] = D === Hh ? D : E
        e[7] = (D === Hh && E !== I) || (Hh === F && E !== G) ? Hh : E
        e[8] = Hh === F ? F : E
      }
      for (let i = 0; i < 9; i++) out[y * 3 + Math.floor(i / 3)]![x * 3 + (i % 3)] = e[i]!
    }
  }
  return out
}

