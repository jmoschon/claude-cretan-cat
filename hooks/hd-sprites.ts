export const HD_CLAWD = (look: ClawdLook): HdArt | undefined => {
  const key = JSON.stringify({ ...look, scale: 1 })
  const cached = clawdCache.get(key)
  if (cached) return cached
  // His box, a yard pixel of room all round: x -2..15, y -1..8.
  const W0 = CLAWD_W + 4
  const H0 = CLAWD_H + 2
  const g: string[][] = Array.from({ length: H0 }, () => new Array<string>(W0).fill('.'))
  const same = (a: Rgb, b: Rgb) => a[0] === b[0] && a[1] === b[1] && a[2] === b[2]
  for (const p of clawdPixels({ ...look, scale: 1 })) {
    const row = g[p.y + 1]
    if (row && p.x + 2 >= 0 && p.x + 2 < W0) row[p.x + 2] = same(p.c, look.eyeColor) ? 'E' : 'B'
  }
  // The body smoothed (eyes count as body for its shape); the eyes stay
  // crisp squares on top.
  const big = scale3x(g.map(r => r.map(c => (c === 'E' ? 'B' : c))))
  g.forEach((r, y) => r.forEach((c, x) => {
    if (c === 'E') for (let i = 0; i < 9; i++) big[y * 3 + Math.floor(i / 3)]![x * 3 + (i % 3)] = 'E'
  }))
  const H = big.length
  const W = big[0]!.length
  const isBody = (x: number, y: number) => x >= 0 && y >= 0 && x < W && y < H && big[y]![x] !== '.'
  const shaded = big.map(r => r.slice())
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (big[y]![x] !== 'B') continue
      if (!isBody(x, y - 1) || !isBody(x, y - 2)) shaded[y]![x] = 'L'
      else if (!isBody(x, y + 1) || !isBody(x + 1, y)) shaded[y]![x] = 'S'
    }
  }
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (big[y]![x] === '.' && (isBody(x + 1, y) || isBody(x - 1, y) || isBody(x, y + 1) || isBody(x, y - 1))) shaded[y]![x] = 'O'
    }
  }
  const art: HdArt = {
    rows: shaded.map(r => r.join('')),
    // Its box starts a yard pixel (S image pixels) above his.
    dy: S,
    palette: { B: look.color, L: lift(look.color, 0.16), S: shadeOf(look.color, 0.84), O: shadeOf(look.color, 0.5), E: look.eyeColor },
  }
  clawdCache.set(key, art)
  return art
}
