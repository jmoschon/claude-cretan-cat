// The high-resolution art ("resolution: high"), drawn HD_SCALE times as
// fine as the yard's own pixels each way: HD_SCALE by HD_SCALE image pixels
// for each pixel of the low-resolution yard (half a terminal cell).
//
// Everything here is optional. A pose, a kitten frame, the sardine or a
// look of Clawd's with no grid of its own is drawn from its low-resolution
// sprite, each pixel a block of HD_SCALE by HD_SCALE, so nothing is ever
// missing; a grid added here replaces that block version at once.
//
// A grid is a list of equal-length strings, one letter an image pixel, '.'
// (or any letter the palette lacks) clear. It stands on the same ground as
// the low-resolution sprite: its bottom row on the sprite's bottom row, and
// centered on the sprite's width; `dx` and `dy` (image pixels, right and
// down) move it from there. It faces right; the yard mirrors it to face left.

